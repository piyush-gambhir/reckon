pub fn links(target: &Path, source: &Path) -> Result<()> {
    if redirected(target) {
        if std::fs::read_link(target).is_ok_and(|p| p == source) {
            return Ok(());
        }
        std::fs::remove_file(target)?;
    } else if target.exists() {
        return Ok(());
    }
    #[cfg(unix)]
    std::os::unix::fs::symlink(source, target)?;
    #[cfg(windows)]
    {
        if source.is_dir() {
            std::os::windows::fs::symlink_dir(source, target)?;
        } else {
            std::fs::copy(source, target)?;
        }
    }
    Ok(())
}
pub fn settings(h: &Path, ctx: &Context, registry: &Registry) -> Value {
    let mut allow = [
        "status",
        "preflight",
        "capabilities",
        "services",
        "resume",
        "report",
        "note",
        "history",
        "verify",
        "collect",
        "task",
        "debug",
        "investigate",
        "monitor",
        "analyze",
        "close",
        "promote",
        "act prepare",
        "act list",
        "act show",
        "act reconcile",
        "brief",
        "check",
    ]
    .iter()
    .map(|c| format!("Bash(reckon {c}:*)"))
    .collect::<std::collections::BTreeSet<_>>();
    let mut ask = std::collections::BTreeSet::new();
    for (cname, conn) in object(&ctx.data["connections"]) {
        let mode = text(&registry[text(&conn["provider"])]["mode"]);
        let rules = [
            format!("Bash(reckon run {cname}:*)"),
            format!("Bash(reckon run {}:*)", text(&conn["provider"])),
        ];
        if mode == "approval" {
            ask.extend(rules);
        } else if ["own", "allowlist"].contains(&mode) {
            allow.extend(rules);
        }
    }
    allow.retain(|r| !ask.contains(r));
    allow.extend([
        "Bash(reckon secrets status:*)".into(),
        "Bash(reckon secrets check:*)".into(),
    ]);
    let mut deny = [
        "act apply",
        "login",
        "use",
        "connect",
        "org",
        "migrate",
        "brief --all-orgs",
        "log --all-envs",
        "routine",
        "watch",
        "spend --all-orgs",
        "secrets setup",
        "secrets set",
        "secrets link",
        "secrets import",
        "secrets recover",
    ]
    .iter()
    .map(|c| format!("Bash(reckon {c}:*)"))
    .collect::<Vec<_>>();
    deny.extend(
        ["security", "/usr/bin/security", "secret-tool", "op"]
            .iter()
            .map(|c| format!("Bash({c}:*)")),
    );
    let secrets = format!("/{}/*/secrets/**", h.join("orgs").display());
    let log = format!("/{}/*/activity.jsonl", h.join("orgs").display());
    deny.extend([
        format!("Edit({log})"),
        format!("Write({log})"),
        format!("Read({secrets})"),
        format!("Edit({secrets})"),
        format!("Write({secrets})"),
    ]);
    let store = format!("/{}/**", h.join("onepassword").display());
    for operation in ["Read", "Edit", "Write"] {
        deny.push(format!("{operation}({store})"));
    }
    json!({"permissions":{"allow":allow,"ask":ask,"deny":deny}})
}
pub fn overview(ctx: &Context, registry: &Registry) -> String {
    let data = &ctx.data;
    let title = if data["name"] == data["id"] {
        text(&data["name"]).to_owned()
    } else {
        format!("{} (`{}`)", text(&data["name"]), text(&data["id"]))
    };
    let envs = strings(&data["environments"])
        .iter()
        .map(|e| {
            if array(&data["production"]).contains(&json!(e)) {
                format!("**{e}** (production)")
            } else {
                e.clone()
            }
        })
        .collect::<Vec<_>>()
        .join(", ");
    let mut lines=vec!["<!-- Generated by reckon open. Edits here are replaced; keep your own notes in CLAUDE.md or knowledge/. -->".into(),String::new(),format!("# Reckon org: {title}"),String::new(),format!("Environments: {envs}."),"The active environment is pinned when the agent starts: run `reckon preflight` first and state it.".into(),String::new(),"## Connections".into(),String::new(),"| Connection | Tool | Environments | Label per environment | Limited to | Account |".into(),"| --- | --- | --- | --- | --- | --- |".into()];
    for (cname, conn) in object(&data["connections"]) {
        let labels = object(&conn["env_labels"])
            .iter()
            .map(|(e, l)| format!("{e}={}", text(l)))
            .collect::<Vec<_>>()
            .join(", ");
        let limits = object(&conn["resources"])
            .iter()
            .map(|(k, v)| format!("{k}: {}", strings(v).join(", ")))
            .collect::<Vec<_>>()
            .join("; ");
        let provider = text(&conn["provider"]);
        lines.push(format!(
            "| `{cname}` | {} | {} | {} | {} | {} |",
            registry[provider]["title"].as_str().unwrap_or(provider),
            conn["env"].as_str().unwrap_or("all"),
            if labels.is_empty() { "-" } else { &labels },
            if limits.is_empty() { "-" } else { &limits },
            conn["account"].as_str().unwrap_or("-").replace('|', "\\|")
        ));
    }
    if object(&data["connections"]).is_empty() {
        lines.push("| (none yet) | | | | | |".into());
    }
    lines.extend([String::new(),"Run tools through Reckon, never directly: `reckon run <connection-or-tool> -- <arguments>`.".into(),"Reckon adds the connection's credentials and forces read-only. Credentials are never available to you.".into(),"Save work in sessions (`reckon task`, `reckon debug`, `reckon run --session`), and facts in `knowledge/`.".into(),String::new()]);
    let mut writes = vec![];
    for op in actions::WRITES {
        let names = object(&data["connections"])
            .iter()
            .filter(|(_, c)| text(&c["provider"]) == op.1)
            .map(|(n, _)| format!("`{n}`"))
            .collect::<Vec<_>>();
        if !names.is_empty() {
            writes.push(format!(
                "- `{}` via {}: {}{}",
                op.0,
                names.join(", "),
                op.2.split_whitespace().collect::<Vec<_>>().join(", "),
                if op.3.is_empty() {
                    String::new()
                } else {
                    format!(
                        " (optional: {})",
                        op.3.split_whitespace().collect::<Vec<_>>().join(", ")
                    )
                }
            ));
        }
    }
    if !writes.is_empty() {
        lines.extend(["## Writes you can prepare".into(), String::new(), "You prepare, the operator applies: `reckon act prepare <write> --session <id> --params '{...}'` (see WORKSPACE.md).".into(), String::new()]);
        lines.extend(writes);
    }
    lines.push(String::new());
    lines.join("\n")
}
pub fn ensure(h: &Path, ctx: &Context, registry: &Registry) -> Result<PathBuf> {
    let code = assets::root(h)?;
    let root = orgs::workspace(h, &ctx.org)?;
    let envs = strings(&ctx.data["environments"]);
    for dir in [
        "knowledge/_shared",
        "sessions",
        "incidents",
        ".claude/skills",
        ".agents/skills",
    ] {
        private_dir(&local_path(&root, dir)?)?;
    }
    for e in &envs {
        private_dir(&local_path(&root, format!("knowledge/{e}"))?)?;
    }
    let templates = code.join("skills/reckon/templates/infra-knowledge");
    for (layer, targets) in [("_shared", vec!["_shared".to_owned()]), ("env", envs)] {
        for template in entries(&templates.join(layer))? {
            if template.extension().is_some_and(|s| s == "md") {
                for target in &targets {
                    let p = local_path(
                        &root,
                        Path::new("knowledge")
                            .join(target)
                            .join(template.file_name().unwrap_or_default()),
                    )?;
                    if !p.exists() {
                        write(&p, read_bytes(&template, 8 * 1048576)?)?;
                    }
                }
            }
        }
    }
    let mut skills = vec![("reckon".to_owned(), code.join("skills/reckon"))];
    // Source installations can also carry adopted tool skills beside the checkout.
    let installed_skills = orgs::code_root().join(".agents/skills");
    for entry in entries(&installed_skills)? {
        let name = entry
            .file_name()
            .unwrap_or_default()
            .to_string_lossy()
            .to_string();
        if name != "reckon" && entry.join("SKILL.md").is_file() {
            skills.push((name, entry.canonicalize()?));
        }
    }
    for (name, source) in skills {
        links(&root.join(".agents/skills").join(&name), &source)?;
        links(&root.join(".claude/skills").join(name), &source)?;
    }
    write(&local_path(&root, "RECKON.md")?, overview(ctx, registry))?;
    write_json(
        &local_path(&root, ".claude/settings.json")?,
        &settings(h, ctx, registry),
    )?;
    for (file, content) in [
        (
            "CLAUDE.md",
            format!(
                "@RECKON.md\n@{}\n\n# Notes for this org\n\n",
                code.join("WORKSPACE.md").display()
            ),
        ),
        (
            "AGENTS.md",
            format!(
                "# Agent guide\n\nRead `RECKON.md` in this folder, then `{}`, the full guide for working in a Reckon org. Run `reckon preflight` before your first query.\n\n# Notes for this org\n\n",
                code.join("WORKSPACE.md").display()
            ),
        ),
    ] {
        let p = local_path(&root, file)?;
        if !p.exists() {
            write(&p, content)?;
        }
    }
    let bin = local_path(h, "bin")?;
    private_dir(&bin)?;
    let link = bin.join(if cfg!(windows) {
        "reckon.exe"
    } else {
        "reckon"
    });
    let exe = std::env::current_exe()?;
    if link != exe && !std::fs::read_link(&link).is_ok_and(|target| target == exe) {
        if link.exists() || redirected(&link) {
            std::fs::remove_file(&link)?;
        }
        links(&link, &exe)?;
    }
    Ok(root)
}
pub fn agent_env(
    h: &Path,
    ctx: &Context,
    registry: &Registry,
    runtime: &str,
) -> process::Environment {
    let prefixes = registry
        .values()
        .flat_map(|s| strings(&s["prefixes"]))
        .collect::<Vec<_>>();
    let named = registry
        .values()
        .flat_map(|s| strings(&s["agent_scrub"]))
        .chain(["KUBECONFIG".into(), "XDG_CONFIG_HOME".into()])
        .collect::<std::collections::BTreeSet<_>>();
    let mut env = std::env::vars()
        .filter(|(k, _)| {
            !k.starts_with("RECKON_")
                && !k.starts_with("OP_")
                && !named.contains(k)
                && !prefixes.iter().any(|p| k.starts_with(p))
        })
        .collect::<process::Environment>();
    for (k, v) in [
        ("RECKON_HOME", h.display().to_string()),
        ("RECKON_ORG", ctx.org.clone()),
        ("RECKON_ENV", ctx.env.clone()),
        ("RECKON_RUNTIME", runtime.into()),
    ] {
        env.insert(k.into(), v);
    }
    let prior_path = env.get("PATH").cloned().unwrap_or_default();
    let paths = std::iter::once(h.join("bin")).chain(std::env::split_paths(&prior_path));
    env.insert(
        "PATH".into(),
        std::env::join_paths(paths)
            .unwrap_or_default()
            .to_string_lossy()
            .to_string(),
    );
    env
}
pub fn launch(
    h: &Path,
    ctx: &Context,
    registry: &Registry,
    runtime: Option<&str>,
    extra: &[String],
) -> Result<i32> {
    let root = ensure(h, ctx, registry)?;
    let runtime = runtime
        .map(str::to_owned)
        .or_else(|| {
            ["claude", "codex"]
                .iter()
                .find(|r| which(r).is_some())
                .map(|r| (*r).into())
        })
        .unwrap_or_default();
    ensure!(
        ["claude", "codex"].contains(&runtime.as_str()) && which(&runtime).is_some(),
        "install Claude Code (claude) or Codex (codex), or name one: reckon open <org>/<env> --runtime claude|codex"
    );
    println!(
        "{}",
        if ctx.production {
            format!("!!! {} · {} (PRODUCTION) !!!", ctx.org, ctx.env)
        } else {
            format!("=== {} · {} ===", ctx.org, ctx.env)
        }
    );
    use std::io::Write;
    std::io::stdout().flush()?;
    let mut cmd = std::process::Command::new(&runtime);
    cmd.args(extra)
        .current_dir(root)
        .env_clear()
        .envs(agent_env(h, ctx, registry, &runtime));
    #[cfg(unix)]
    {
        use std::os::unix::process::CommandExt;
        Err(cmd.exec().into())
    }
    #[cfg(not(unix))]
    {
        Ok(cmd.status()?.code().unwrap_or(1))
    }
}
