"""Each org's agent folder, and launching Claude Code or Codex in it.

The agent runs in $RECKON_HOME/orgs/<org>/workspace. Both runtimes key memory,
conversation history and project settings by folder, so one folder per org keeps
each business's facts in its own conversations. Credentials stay one level up,
outside the folder the agent works in.
"""
import json
import os
from pathlib import Path
import shutil

from . import orgs
from .store import local_path, private_dir, write, write_json

MARK = "<!-- Generated by reckon open. Edits here are replaced; keep your own notes in CLAUDE.md or knowledge/. -->"


def links(target, source):
    """Point target at source; replace only links Reckon owns."""
    if target.is_symlink():
        if os.readlink(target) == str(source):
            return
        target.unlink()
    elif target.exists():
        return
    target.symlink_to(source, target_is_directory=True)


def skills(code):
    found = {"reckon": code / "skills" / "reckon"}
    installed = code / ".agents" / "skills"
    if installed.is_dir():
        for entry in sorted(installed.iterdir()):
            if entry.name != "reckon" and (entry / "SKILL.md").is_file():
                found[entry.name] = entry.resolve()
    return found


def overview(h, ctx, registry):
    data = ctx["data"]
    title = data["name"] + (" (`" + data["id"] + "`)" if data["name"] != data["id"] else "")
    lines = [MARK, "", "# Reckon org: " + title, "",
             "Environments: " + ", ".join("**" + e + "** (production)" if e in data["production"] else e for e in data["environments"]) + ".",
             "The active environment is pinned when the agent starts: run `reckon preflight` first and state it.", "",
             "## Connections", "", "| Connection | Tool | Environments | Label per environment | Limited to | Account |",
             "| --- | --- | --- | --- | --- | --- |"]
    for cname, conn in sorted(data["connections"].items()):
        labels = ", ".join(e + "=" + l for e, l in sorted(conn.get("env_labels", {}).items())) or "-"
        limits = "; ".join(k + ": " + ", ".join(v) for k, v in sorted(conn.get("resources", {}).items())) or "-"
        lines.append("| `" + cname + "` | " + registry[conn["provider"]].get("title", conn["provider"]) + " | " + (conn.get("env") or "all") + " | " + labels +
                     " | " + limits + " | " + (conn.get("account") or "-").replace("|", "\\|") + " |")
    if not data["connections"]:
        lines.append("| (none yet) | | | | | |")
    lines += ["", "Run tools through Reckon, never directly: `reckon run <connection-or-tool> -- <arguments>`.",
              "Reckon adds the connection's credentials and forces read-only. Credentials are never available to you.",
              "Save work in sessions (`reckon task`, `reckon debug`, `reckon run --session`), and facts in `knowledge/`.", ""]
    return "\n".join(lines)


def settings(h, ctx, registry):
    """Claude Code permissions: reads through Reckon run freely, logins and secrets are off limits."""
    allow = ["Bash(reckon " + c + ":*)" for c in ("status", "preflight", "capabilities", "services", "resume", "report",
                                                 "note", "history", "verify", "collect", "task", "debug", "investigate",
                                                 "monitor", "analyze", "close", "promote", "act prepare", "act list", "act show", "act reconcile", "brief", "check")]
    ask = []
    for cname, conn in sorted(ctx["data"]["connections"].items()):
        mode = registry[conn["provider"]].get("mode")
        rules = ["Bash(reckon run " + cname + ":*)", "Bash(reckon run " + conn["provider"] + ":*)"]
        (ask if mode == "approval" else allow if mode in ("own", "allowlist") else []).extend(rules)
    # Claude Code reads "//path" as an absolute path.
    secrets = "/" + str(h / "orgs") + "/*/secrets/**"
    log = "/" + str(h / "orgs") + "/*/activity.jsonl"
    deny = ["Bash(reckon act apply:*)", "Bash(reckon login:*)", "Bash(reckon use:*)", "Bash(reckon connect:*)", "Bash(reckon org:*)", "Bash(reckon migrate:*)",
            "Bash(reckon brief --all-orgs:*)", "Bash(reckon log --all-envs:*)", "Bash(reckon routine:*)", "Bash(reckon watch:*)", "Bash(reckon spend --all-orgs:*)",
            # Secret references are read by reckon run, never by the agent.
            "Bash(security:*)", "Bash(/usr/bin/security:*)", "Bash(secret-tool:*)", "Bash(op:*)",
            "Edit(" + log + ")", "Write(" + log + ")",
            "Read(" + secrets + ")", "Edit(" + secrets + ")", "Write(" + secrets + ")"]
    return {"permissions": {"allow": sorted(set(allow) - set(ask)), "ask": sorted(set(ask)), "deny": deny}}


def ensure(h, ctx, registry):
    org, data = ctx["org"], ctx["data"]
    code = orgs.code_root()
    root = orgs.workspace(h, org)
    for directory in ["knowledge/_shared", "sessions", "incidents", ".claude/skills", ".agents/skills"] + ["knowledge/" + e for e in data["environments"]]:
        private_dir(local_path(root, directory))
    templates = code / "skills" / "reckon" / "templates" / "infra-knowledge"
    for layer, targets in (("_shared", ["_shared"]), ("env", data["environments"])):
        for template in sorted((templates / layer).glob("*.md")):
            for target in targets:
                path = local_path(root, "knowledge", target, template.name)
                if not path.exists():
                    write(path, template.read_text())
    for skill, source in skills(code).items():
        links(root / ".agents" / "skills" / skill, source)
        links(root / ".claude" / "skills" / skill, source)
    write(root / "RECKON.md", overview(h, ctx, registry))
    write_json(root / ".claude" / "settings.json", settings(h, ctx, registry))
    if not (root / "CLAUDE.md").exists():
        write(root / "CLAUDE.md", "@RECKON.md\n@" + str(code / "WORKSPACE.md") + "\n\n# Notes for this org\n\n")
    if not (root / "AGENTS.md").exists():
        write(root / "AGENTS.md", "# Agent guide\n\nRead `RECKON.md` in this folder, then `" + str(code / "WORKSPACE.md") +
              "`, the full guide for working in a Reckon org. Run `reckon preflight` before your first query.\n\n# Notes for this org\n\n")
    command = local_path(h, "bin")
    private_dir(command)
    link = command / "reckon"
    target = code / "scripts" / "reckon.py"
    if not (link.is_symlink() and os.readlink(link) == str(target)):
        if link.is_symlink() or link.exists():
            link.unlink()
        link.symlink_to(target)
    return root


def agent_env(h, ctx, registry):
    """The operator's environment minus every provider credential, plus the pinned context."""
    prefixes = tuple(p for spec in registry.values() for p in spec["prefixes"])
    # Credentials some CLIs read under their own names, outside the provider prefixes.
    named = {"KUBECONFIG", "XDG_CONFIG_HOME"} | {k for spec in registry.values() for k in spec.get("agent_scrub", [])}
    env = {k: v for k, v in os.environ.items() if not k.startswith(prefixes) and not k.startswith("RECKON_") and k not in named}
    env.update(RECKON_HOME=str(h), RECKON_ORG=ctx["org"], RECKON_ENV=ctx["env"])
    env["PATH"] = str(h / "bin") + os.pathsep + env.get("PATH", "")
    return env


def launch(h, ctx, registry, runtime=None, extra=()):
    root = ensure(h, ctx, registry)
    runtime = runtime or next((r for r in ("claude", "codex") if shutil.which(r)), None)
    if runtime not in ("claude", "codex") or not shutil.which(runtime):
        raise ValueError("install Claude Code (claude) or Codex (codex), or name one: reckon open <org>/<env> claude|codex")
    banner = ctx["org"] + " · " + ctx["env"]
    print(("!!! " + banner + " (PRODUCTION) !!!") if ctx["production"] else ("=== " + banner + " ==="))
    os.chdir(root)
    os.execvpe(runtime, [runtime] + list(extra), agent_env(h, ctx, registry))
